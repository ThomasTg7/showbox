// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { isPublicationValid } from "../schedule";
import { PublicationControls } from "./publication-controls";

afterEach(cleanup);

function setup(props: Partial<React.ComponentProps<typeof PublicationControls>> = {}) {
  const onChange = vi.fn();
  render(<PublicationControls status="draft" publishAt={null} onChange={onChange} previewHref="/boxeadores/x?preview=t" {...props} />);
  return onChange;
}

describe("PublicationControls", () => {
  it("shows the current state and submits it in hidden inputs", () => {
    setup({ status: "published" });
    expect(screen.getByRole("radio", { name: "Publicado" })).toBeChecked();
    expect((document.querySelector('input[name="status"]') as HTMLInputElement).value).toBe("published");
  });

  it("asks for date and time when scheduling and reports an invalid state until they are filled", () => {
    const onChange = setup();
    fireEvent.click(screen.getByRole("radio", { name: "Programar" }));
    expect(screen.getByText("Elige fecha y hora")).toBeInTheDocument();
    expect(onChange).toHaveBeenLastCalledWith({ status: "scheduled", publishAt: null });
    expect(isPublicationValid({ status: "scheduled", publishAt: null })).toBe(false);

    fireEvent.change(screen.getByLabelText("Fecha"), { target: { value: "2026-10-15" } });
    fireEvent.change(screen.getByLabelText("Hora"), { target: { value: "20:00" } });
    expect(screen.queryByText("Elige fecha y hora")).not.toBeInTheDocument();
    expect(onChange).toHaveBeenLastCalledWith({ status: "scheduled", publishAt: new Date("2026-10-16T01:00:00Z") });
    expect((document.querySelector('input[name="publishAt"]') as HTMLInputElement).value).toBe("2026-10-16T01:00:00.000Z");
  });

  it("clears the schedule when going back to draft", () => {
    const onChange = setup({ status: "scheduled", publishAt: new Date("2026-10-15T23:00:00Z") });
    fireEvent.click(screen.getByRole("radio", { name: "Borrador" }));
    expect(onChange).toHaveBeenLastCalledWith({ status: "draft", publishAt: null });
    expect(screen.queryByLabelText("Fecha")).not.toBeInTheDocument();
  });

  it("opens the preview link in a new tab", () => {
    setup();
    const link = screen.getByRole("link", { name: /Vista previa/ });
    expect(link).toHaveAttribute("href", "/boxeadores/x?preview=t");
    expect(link).toHaveAttribute("target", "_blank");
  });

  it("resolves the preview link on click when it is generated by the server", async () => {
    const open = vi.spyOn(window, "open").mockReturnValue({ location: { href: "" }, close: vi.fn() } as unknown as Window);
    const resolve = vi.fn().mockResolvedValue("/boxeadores/x?preview=fresh");
    setup({ previewHref: resolve });
    fireEvent.click(screen.getByRole("button", { name: /Vista previa/ }));
    await vi.waitFor(() => expect(resolve).toHaveBeenCalled());
    open.mockRestore();
  });
});
